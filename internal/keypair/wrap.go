// Labels that start every authenticated header, so a wrapped key or a MAC
// from this format can never be mistaken for one from another format or a
// future version (the same idea as D8's "securestore/v1").
const (
	wrapLabel      = "securestore/keypair/v1"
	publicMACLabel = "securestore/keypair-public/v1"
)

// PublicMACKeySize is the length of the key that authenticates public keys:
// crypto.DeriveKey(MASTER_KEY, "keypair-public-mac") (D42).
const PublicMACKeySize = 32

// gcmOverhead is the 12-byte nonce plus the 16-byte tag that
// NewGCMWithRandomNonce adds to every ciphertext.
const gcmOverhead = 12 + 16

// lengthPrefixed encodes fields as 4-byte big-endian length || bytes, one
// after another. The lengths make the encoding unambiguous: ("ab", "c") and
// ("a", "bc") give different bytes (D8 uses the same encoding).
func lengthPrefixed(fields ...[]byte) []byte {
	var out []byte
	for _, f := range fields {
		// Unreachable: every field is a label, an ID, a purpose, a DER key
		// or a hash. The check makes the conversion provably safe.
		if uint64(len(f)) > math.MaxUint32 {
			panic("keypair: field too long")
		}
		out = binary.BigEndian.AppendUint32(out, uint32(len(f))) // #nosec G115 -- bounded by the check above.
		out = append(out, f...)
	}
	return out
}

// wrapAAD is the associated data of a wrapped private key. GCM checks it on
// unwrap without encrypting it, so a wrapped key only opens for the same
// user, the same purpose and the same public key (D41). Copying it into
// another account, swapping encryption and signing, or replacing the public
// key next to it all make the unwrap fail.
func wrapAAD(userID bson.ObjectID, p Purpose, fingerprint []byte) []byte {
	return lengthPrefixed([]byte(wrapLabel), userID[:], []byte(p), fingerprint)
}

// newGCM returns AES-256-GCM under kek with a random 96-bit nonce per Seal,
// generated by the standard library from crypto/rand (as D10 does).
func newGCM(kek []byte) (cipher.AEAD, error) {
	if len(kek) != kekSize {
		return nil, fmt.Errorf("keypair: KEK must be %d bytes, got %d", kekSize, len(kek))
	}
	block, err := aes.NewCipher(kek)
	if err != nil {
		return nil, err
	}
	return cipher.NewGCMWithRandomNonce(block)
}

// wrapPrivate encrypts a PKCS#8 private key under kek, bound to aad. The
// output is nonce || ciphertext || tag.
func wrapPrivate(kek, pkcs8, aad []byte) ([]byte, error) {
	if len(pkcs8) == 0 {
		return nil, errors.New("keypair: wrap: private key is empty")
	}
	aead, err := newGCM(kek)
	if err != nil {
		return nil, err
	}
	// The nonce argument must be nil: this AEAD makes its own random nonce.
	return aead.Seal(nil, nil, pkcs8, aad), nil // #nosec G407 -- nonce is random, generated inside NewGCMWithRandomNonce.
}

// unwrapPrivate reverses wrapPrivate. Every failure (wrong KEK, modified or
// truncated blob, different aad) returns ErrUnlock.
func unwrapPrivate(kek, wrapped, aad []byte) ([]byte, error) {
	aead, err := newGCM(kek)
	if err != nil {
		return nil, err
	}
	// A real blob holds at least one key byte on top of nonce and tag.
	if len(wrapped) <= aead.Overhead() {
		return nil, ErrUnlock
	}
	pkcs8, err := aead.Open(nil, nil, wrapped, aad)
	if err != nil {
		return nil, ErrUnlock
	}
	return pkcs8, nil
}

// publicMAC authenticates the public half of a pair under macKey, a subkey
// of MASTER_KEY (D42). The user ID and purpose are included so a valid pair
// can't be moved to another user or slot, and CreatedAt so the date shown
// can't be changed either. CreatedAt is in milliseconds, MongoDB's date
// precision, so the MAC survives a round trip through the database.
func publicMAC(macKey []byte, userID bson.ObjectID, p Purpose, sp *StoredPair) []byte {
	m := hmac.New(sha256.New, macKey)
	m.Write(lengthPrefixed( // hash.Hash.Write never returns an error.
		[]byte(publicMACLabel),
		userID[:],
		[]byte(p),
		sp.PublicDER,
		sp.Fingerprint,
		strconv.AppendInt(nil, sp.CreatedAt.UnixMilli(), 10),
	))
	return m.Sum(nil)
}

// newStoredPair builds the stored form of priv: public key, fingerprint, the
// private key wrapped under kek, and the public MAC.
func newStoredPair(kek, macKey []byte, userID bson.ObjectID, p Purpose, priv *rsa.PrivateKey, now time.Time) (StoredPair, error) {
	pubDER, err := x509.MarshalPKIXPublicKey(&priv.PublicKey)
	if err != nil {
		return StoredPair{}, fmt.Errorf("keypair: encode public key: %w", err)
	}
	fp := sha256.Sum256(pubDER)

	pkcs8, err := x509.MarshalPKCS8PrivateKey(priv)
	if err != nil {
		return StoredPair{}, fmt.Errorf("keypair: encode private key: %w", err)
	}
	// Best effort: shortens how long the plaintext private key sits in
	// memory (D13).
	defer clear(pkcs8)

	wrapped, err := wrapPrivate(kek, pkcs8, wrapAAD(userID, p, fp[:]))
	if err != nil {
		return StoredPair{}, err
	}
	sp := StoredPair{
		PublicDER:      pubDER,
		Fingerprint:    fp[:],
		WrappedPrivate: wrapped,
		CreatedAt:      now.UTC().Truncate(time.Millisecond),
	}
	sp.PublicMAC = publicMAC(macKey, userID, p, &sp)
	return sp, nil
}

// verifyPublic checks the stored public half and returns the public key.
// Any mismatch wraps ErrCorrupt.
func verifyPublic(macKey []byte, userID bson.ObjectID, p Purpose, sp *StoredPair) (*rsa.PublicKey, error) {
	if !hmac.Equal(sp.PublicMAC, publicMAC(macKey, userID, p, sp)) {
		return nil, fmt.Errorf("%w: %s public key MAC mismatch", ErrCorrupt, p)
	}
	// Implied by the MAC (we only MAC a correct fingerprint), but cheap,
	// and it keeps the fingerprint honest even if the MAC key leaks.
	if fp := sha256.Sum256(sp.PublicDER); !bytes.Equal(fp[:], sp.Fingerprint) {
		return nil, fmt.Errorf("%w: %s fingerprint mismatch", ErrCorrupt, p)
	}
	key, err := x509.ParsePKIXPublicKey(sp.PublicDER)
	if err != nil {
		return nil, fmt.Errorf("%w: %s public key: %v", ErrCorrupt, p, err)
	}
	pub, ok := key.(*rsa.PublicKey)
	if !ok || pub.N.BitLen() != KeyBits {
		return nil, fmt.Errorf("%w: %s public key is not RSA-%d", ErrCorrupt, p, KeyBits)
	}
	return pub, nil
}

// FormatFingerprint formats a SHA-256 fingerprint as lowercase hex in groups
// of four ("1a2b 3c4d …"), so two people can compare it by reading it out.
// The plain hex (without spaces) equals sha256sum of the DER public key.
func FormatFingerprint(fp []byte) string {
	h := hex.EncodeToString(fp)
	var b strings.Builder
	for i := 0; i < len(h); i += 4 {
		if i > 0 {
			b.WriteByte(' ')
		}
		b.WriteString(h[i:min(i+4, len(h))])
	}
	return b.String()
}

// PublicKeyPEM encodes pub as a PEM "PUBLIC KEY" block (PKIX), the format
// OpenSSL and most tools read.
func PublicKeyPEM(pub *rsa.PublicKey) ([]byte, error) {
	der, err := x509.MarshalPKIXPublicKey(pub)
	if err != nil {
		return nil, fmt.Errorf("keypair: encode public key: %w", err)
	}
	return pem.EncodeToMemory(&pem.Block{Type: "PUBLIC KEY", Bytes: der}), nil
}
